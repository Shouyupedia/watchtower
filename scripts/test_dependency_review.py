"""Tests for scripts/dependency-review.py.

Run from the repository root with:

    python -I -m unittest discover -s scripts -p "test_*.py" -v
"""

import http.server
import importlib.util
import io
import json
import threading
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

SCRIPT = Path(__file__).resolve().parent / "dependency-review.py"
REPO_ROOT = SCRIPT.resolve().parent.parent

_spec = importlib.util.spec_from_file_location("dependency_review", SCRIPT)
assert _spec is not None and _spec.loader is not None
dr = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(dr)


def write_file(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def run_main(argv):
    stdout = io.StringIO()
    stderr = io.StringIO()
    with redirect_stdout(stdout), redirect_stderr(stderr):
        code = dr.main(list(argv))
    return code, stdout.getvalue(), stderr.getvalue()


class _StubServer:
    """Minimal local HTTP server to simulate OSV.dev responses and failures."""

    def __init__(self, handler_fn):
        self._handler_fn = handler_fn
        outer = self

        class Handler(http.server.BaseHTTPRequestHandler):
            def do_POST(self):
                length = int(self.headers.get("Content-Length", "0"))
                body = self.rfile.read(length).decode("utf-8")
                status, payload = outer._handler_fn(json.loads(body))
                encoded = payload.encode("utf-8") if isinstance(payload, str) else json.dumps(payload).encode("utf-8")
                self.send_response(status)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(encoded)))
                self.end_headers()
                self.wfile.write(encoded)

            def log_message(self, format, *args):
                pass

        self._server = http.server.HTTPServer(("127.0.0.1", 0), Handler)
        self._thread = threading.Thread(target=self._server.serve_forever, daemon=True)

    def __enter__(self):
        self._thread.start()
        host, port = self._server.server_address
        return f"http://{host}:{port}/v1/querybatch"

    def __exit__(self, *exc):
        self._server.shutdown()
        self._server.server_close()
        self._thread.join(timeout=5)


class ParseGoModTests(unittest.TestCase):
    def test_parses_single_and_block_requires(self):
        text = """
module example.com/app

go 1.26.0

require example.com/direct v1.2.3

require (
    example.com/a v0.1.0 // indirect
    "example.com/b" v2.3.4+incompatible
)
"""
        deps = dr.parse_go_mod("go.mod", text)
        self.assertEqual(
            deps,
            {
                dr.Dependency("Go", "example.com/direct", "1.2.3"),
                dr.Dependency("Go", "example.com/a", "0.1.0"),
                dr.Dependency("Go", "example.com/b", "2.3.4+incompatible"),
            },
        )

    def test_applies_replace_directives(self):
        text = """
module example.com/app

go 1.26.0

require (
    example.com/old v1.0.0
    example.com/local v0.0.0
)

replace (
    example.com/old v1.0.0 => example.com/new v1.0.1
    example.com/local => ./localmod
)
"""
        deps = dr.parse_go_mod("go.mod", text)
        self.assertEqual(deps, {dr.Dependency("Go", "example.com/new", "1.0.1")})

    def test_skips_tool_and_retract_blocks(self):
        text = """
module example.com/tools

go 1.26.4

tool (
    example.com/cli/cmd/tool
)

require example.com/cli v1.0.0 // indirect
"""
        deps = dr.parse_go_mod("tools/go.mod", text)
        self.assertEqual(deps, {dr.Dependency("Go", "example.com/cli", "1.0.0")})

    def test_unclosed_block_fails(self):
        with self.assertRaises(dr.ReviewError):
            dr.parse_go_mod("go.mod", "module m\nrequire (\n\texample.com/a v1.0.0\n")

    def test_malformed_require_entry_fails(self):
        with self.assertRaises(dr.ReviewError):
            dr.parse_go_mod("go.mod", "module m\nrequire example.com/onlymod\n")


class ParseRequirementsTests(unittest.TestCase):
    def test_parses_hashed_uv_lockfile(self):
        text = """
# Generated by uv
Click==8.3.1 ; sys_platform == 'win32' \\
    --hash=sha256:aaaa \\
    --hash=sha256:bbbb
    # via mkdocs
my_pkg.name[extra]==1.2.3 \\
    --hash=sha256:cccc
"""
        deps = dr.parse_requirements_txt("docs-requirements.txt", text)
        self.assertEqual(
            deps,
            {
                dr.Dependency("PyPI", "click", "8.3.1"),
                dr.Dependency("PyPI", "my-pkg-name", "1.2.3"),
            },
        )

    def test_rejects_unpinned_requirement(self):
        with self.assertRaises(dr.ReviewError):
            dr.parse_requirements_txt("docs-requirements.txt", "requests>=2.30.0\n")

    def test_rejects_extra_index_url_option(self):
        with self.assertRaises(dr.ReviewError):
            dr.parse_requirements_txt(
                "docs-requirements.txt", "--extra-index-url https://evil.example/\n"
            )


class ParseWorkflowActionsTests(unittest.TestCase):
    def test_parses_block_and_flow_style_uses(self):
        sha = "3d3c42e5aac5ba805825da76410c181273ba90b1"
        text = f"""
jobs:
  build:
    steps:
      - uses: actions/checkout@{sha} # v7.0.1
      - {{ name: flow, uses: "actions/setup-go@v5.0.0" }}
      - uses: ./.github/actions/local
      - uses: docker://alpine:3.20
"""
        deps = dr.parse_workflow_actions(".github/workflows/ci.yml", text)
        self.assertEqual(
            deps,
            {
                dr.Dependency("GitHub Actions", "actions/checkout", sha, commit=sha),
                dr.Dependency("GitHub Actions", "actions/setup-go", "v5.0.0"),
            },
        )


class RealRepoManifestTests(unittest.TestCase):
    def test_real_repository_manifests_parse_cleanly(self):
        manifests = dr.load_manifests_from_dir(REPO_ROOT)
        self.assertIn("go.mod", manifests)
        self.assertIn("tools/go.mod", manifests)
        self.assertIn("docs-requirements.txt", manifests)
        self.assertIn(".github/zizmor-requirements.txt", manifests)
        deps = dr.collect_dependencies(manifests)
        self.assertTrue(any(d.ecosystem == "Go" for d in deps))
        self.assertTrue(any(d.ecosystem == "PyPI" for d in deps))
        self.assertTrue(any(d.ecosystem == "GitHub Actions" for d in deps))


class EndToEndReviewTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.base = Path(self._tmp.name) / "base"
        self.head = Path(self._tmp.name) / "head"
        self.base.mkdir()
        self.head.mkdir()

    def test_no_dependency_change_passes_without_querying_osv(self):
        mod = "module example.com/app\n\ngo 1.26.0\n\nrequire example.com/a v1.0.0\n"
        write_file(self.base / "go.mod", mod)
        write_file(self.head / "go.mod", mod)
        # Unreachable endpoint proves no query was needed when nothing changed.
        code, out, err = run_main(
            [
                "--base-dir", str(self.base),
                "--head-dir", str(self.head),
                "--osv-url", "http://127.0.0.1:1/unreachable",
            ]
        )
        self.assertEqual(code, 0, err)
        self.assertIn("no added or updated dependencies", out)

    def test_known_vulnerable_upgrade_fails(self):
        write_file(
            self.base / "go.mod",
            "module example.com/app\n\ngo 1.26.0\n\nrequire golang.org/x/net v0.63.0\n",
        )
        write_file(
            self.head / "go.mod",
            "module example.com/app\n\ngo 1.26.0\n\nrequire golang.org/x/net v0.17.0\n",
        )

        def handler(payload):
            self.assertEqual(len(payload["queries"]), 1)
            return 200, {"results": [{"vulns": [{"id": "GO-2024-9999"}]}]}

        with _StubServer(handler) as url:
            code, _, err = run_main(
                [
                    "--base-dir", str(self.base),
                    "--head-dir", str(self.head),
                    "--osv-url", url,
                ]
            )
        self.assertEqual(code, 1)
        self.assertIn("golang.org/x/net@0.17.0", err)
        self.assertIn("GO-2024-9999", err)

    def test_clean_upgrade_passes(self):
        write_file(
            self.base / "docs-requirements.txt",
            "click==8.3.0 \\\n    --hash=sha256:aaaa\n",
        )
        write_file(
            self.head / "docs-requirements.txt",
            "click==8.3.1 \\\n    --hash=sha256:bbbb\n",
        )

        def handler(payload):
            self.assertEqual(
                payload["queries"],
                [{"package": {"ecosystem": "PyPI", "name": "click"}, "version": "8.3.1"}],
            )
            return 200, {"results": [{}]}

        with _StubServer(handler) as url:
            code, out, err = run_main(
                [
                    "--base-dir", str(self.base),
                    "--head-dir", str(self.head),
                    "--osv-url", url,
                ]
            )
        self.assertEqual(code, 0, err)
        self.assertIn("1 added/updated dependency(ies) checked against OSV, 0 vulnerabilities", out)

    def test_osv_http_error_fails_closed(self):
        write_file(self.base / "go.mod", "module example.com/app\n\ngo 1.26.0\n")
        write_file(
            self.head / "go.mod",
            "module example.com/app\n\ngo 1.26.0\n\nrequire example.com/a v1.0.0\n",
        )

        with _StubServer(lambda _payload: (503, {"error": "unavailable"})) as url:
            code, _, err = run_main(
                [
                    "--base-dir", str(self.base),
                    "--head-dir", str(self.head),
                    "--osv-url", url,
                ]
            )
        self.assertEqual(code, 1)
        self.assertIn("HTTP 503", err)

    def test_osv_mismatched_results_count_fails_closed(self):
        write_file(self.base / "go.mod", "module example.com/app\n\ngo 1.26.0\n")
        write_file(
            self.head / "go.mod",
            "module example.com/app\n\ngo 1.26.0\n\nrequire example.com/a v1.0.0\n",
        )

        with _StubServer(lambda _payload: (200, {"results": []})) as url:
            code, _, err = run_main(
                [
                    "--base-dir", str(self.base),
                    "--head-dir", str(self.head),
                    "--osv-url", url,
                ]
            )
        self.assertEqual(code, 1)
        self.assertIn("mismatched", err)

    def test_legacy_unpinned_base_allows_strict_pinned_head(self):
        write_file(self.base / "docs-requirements.txt", "mkdocs\n")
        write_file(
            self.head / "docs-requirements.txt",
            "mkdocs==1.6.1 \\\n    --hash=sha256:aaaa\n",
        )

        with _StubServer(lambda payload: (200, {"results": [{}] * len(payload["queries"])})) as url:
            code, out, err = run_main(
                [
                    "--base-dir", str(self.base),
                    "--head-dir", str(self.head),
                    "--osv-url", url,
                ]
            )
        self.assertEqual(code, 0, err)
        self.assertIn("1 added/updated dependency(ies) checked against OSV", out)

    def test_osv_unreachable_fails_closed(self):
        write_file(self.base / "go.mod", "module example.com/app\n\ngo 1.26.0\n")
        write_file(
            self.head / "go.mod",
            "module example.com/app\n\ngo 1.26.0\n\nrequire example.com/a v1.0.0\n",
        )
        code, _, err = run_main(
            [
                "--base-dir", str(self.base),
                "--head-dir", str(self.head),
                "--osv-url", "http://127.0.0.1:1/unreachable",
                "--timeout", "2",
            ]
        )
        self.assertEqual(code, 1)
        self.assertIn("OSV query failed", err)


if __name__ == "__main__":
    unittest.main()
